package fuzz

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"

	harness "github.com/thec1oud/dql/conformance/harness/go"
	"github.com/thec1oud/dql/runtime/go/dql"
)

// Package is the generated Go package of one seed's catalog on one dialect,
// as a run of the seed's scenario needs it: its constructors, column
// handles, shapes and reads, by the names the scenario uses.
type Package struct {
	Seed    uint64
	Dialect string
	// Catalog is the catalog the package's code reads, on source fz.
	Catalog     string
	New         func(*dql.Executor) any
	NewExecutor func(context.Context, dql.Driver, dql.Config, ...dql.Option) (*dql.Executor, error)
	Tables      map[string]any
	Shapes      any
	Selects     map[string]any
}

// Run is a differential run: the seeds it generates, the dql binary that
// generates their code, the servers each dialect's databases are made on,
// by dialect, and the directory it works in.
type Run struct {
	Seeds []uint64
	DQL   string
	Bases map[string]string
	Dir   string
	// Repo is the repository's root, whose workspace the generated
	// packages build in.
	Repo string
}

// sources are the dql.yaml source entries reading each dialect's database,
// whose connection is in FUZZ_URL, and the dialects their code is emitted
// for.
var sources = map[string]struct{ source, dialect string }{
	"postgres":  {"plugin: pg-live\n    connection: env:FUZZ_URL\n    namespaces: [public]\n    default-namespace: public", "postgres"},
	"mysql":     {"plugin: mysql-live\n    connection: env:FUZZ_URL", "mysql"},
	"mariadb":   {"plugin: mysql-live\n    connection: env:FUZZ_URL", "mysql"},
	"sqlite":    {"plugin: sqlite-live\n    connection: env:FUZZ_URL", "sqlite"},
	"sqlserver": {"plugin: sqlserver-live\n    connection: env:FUZZ_URL\n    default-namespace: dbo", "sqlserver"},
}

// pkgName is the name of the package of seed on dialect.
func pkgName(seed uint64, dialect string) string { return fmt.Sprintf("s%d%s", seed, dialect) }

// Prepare generates the package of each seed on each dialect that holds
// its catalog, with its bundle, from a database it creates and drops, and
// writes the module that runs their scenarios: Dir/s<seed>/<dialect>, and
// Dir/run_test.go. It returns the packages it wrote, by directory.
func (r *Run) Prepare(ctx context.Context) ([]string, error) {
	var dirs, imports, pkgs []string
	for _, seed := range r.Seeds {
		c := Generate(seed)
		for _, d := range Dialects {
			if len(c.Lacks(d)) > 0 {
				continue
			}
			dir := filepath.Join(r.Dir, fmt.Sprintf("s%d", seed), d)
			if err := r.generate(ctx, c, d, dir); err != nil {
				return nil, fmt.Errorf("seed %d on %s: %w", seed, d, err)
			}
			dirs = append(dirs, dir)
			imports = append(imports, fmt.Sprintf("\t%q", "fuzzrun/"+filepath.ToSlash(must(filepath.Rel(r.Dir, dir)))))
			pkgs = append(pkgs, "\t\t"+pkgName(seed, d)+".Package,")
		}
	}
	work, err := os.ReadFile(filepath.Join(r.Repo, "go.work"))
	if err != nil {
		return nil, err
	}
	// The workspace's modules, at their absolute paths, and the run's.
	uses := regexp.MustCompile(`(?m)^\t\./(\S*)$`).ReplaceAllString(string(work), "\t"+filepath.ToSlash(r.Repo)+"/$1")
	uses = strings.Replace(uses, "use (\n", "use (\n\t.\n", 1)
	files := map[string]string{
		"go.work": uses,
		"go.mod":  "module fuzzrun\n\ngo 1.25.0\n",
		"run_test.go": "// Code generated by the dql fuzzer. DO NOT EDIT.\n\npackage run\n\nimport (\n\t\"testing\"\n\n\t\"github.com/thec1oud/dql/conformance/fuzz\"\n" +
			strings.Join(imports, "\n") + "\n)\n\nfunc TestRun(t *testing.T) {\n\tfuzz.RunAll(t, []fuzz.Package{\n" + strings.Join(pkgs, "\n") + "\n\t})\n}\n",
	}
	if sum, err := os.ReadFile(filepath.Join(r.Repo, "go.work.sum")); err == nil {
		files["go.work.sum"] = string(sum)
	}
	for name, text := range files {
		if err := os.WriteFile(filepath.Join(r.Dir, name), []byte(text), 0o644); err != nil {
			return nil, err
		}
	}
	return dirs, nil
}

// must returns v, whose error cannot happen.
func must[T any](v T, _ error) T { return v }

// generate creates c's database on dialect d, generates its package and
// bundle into dir, with the package's glue, and drops the database.
func (r *Run) generate(ctx context.Context, c *Catalog, d, dir string) error {
	script, _ := c.Script(d)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	file := filepath.Join(dir, "catalog.sql")
	if err := os.WriteFile(file, []byte(script), 0o644); err != nil {
		return err
	}
	dsn, drop, err := harness.Matrix[d]["shop"].Database(ctx, r.Bases[d], file)
	if err != nil {
		return err
	}
	defer drop()
	src := sources[d]
	name := pkgName(c.Seed, d)
	config := fmt.Sprintf("sources:\n  - %s\n    catalog: fz\nemit:\n  - plugin: go\n    dialect: %s\n    package: %s\n    out: .\n", src.source, src.dialect, name)
	if err := os.WriteFile(filepath.Join(dir, "dql.yaml"), []byte(config), 0o644); err != nil {
		return err
	}
	cmd := exec.CommandContext(ctx, r.DQL, "generate", "-config", "dql.yaml", "-bundle", "bundle.json")
	cmd.Dir = dir
	// sqlite-live reads a file path, not a driver DSN.
	conn := strings.TrimPrefix(strings.SplitN(dsn, "?", 2)[0], "file:")
	if d != "sqlite" {
		conn = dsn
	}
	cmd.Env = append(os.Environ(), "FUZZ_URL="+conn)
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("dql generate: %w\n%s", err, out)
	}
	return os.WriteFile(filepath.Join(dir, "dql-fuzz.go"), []byte(glue(c, d, name)), 0o644)
}

// glue is the file of package name that describes it as a Package.
func glue(c *Catalog, d, name string) string {
	var tables, selects []string
	for _, t := range c.Tables {
		g := strings.ToUpper(t.Name[:1]) + t.Name[1:]
		tables = append(tables, fmt.Sprintf("\t\t%q: %s,", t.Name, g))
		selects = append(selects, fmt.Sprintf("\t\t%q: Select[%sFull, %sTable],", t.Name+"_full", g, g))
	}
	return fmt.Sprintf(`// Code generated by the dql fuzzer. DO NOT EDIT.

package %s

import (
	"github.com/thec1oud/dql/conformance/fuzz"
	"github.com/thec1oud/dql/runtime/go/dql"
)

// Package is this package, as the fuzzer runs it.
var Package = fuzz.Package{
	Seed:        %d,
	Dialect:     %q,
	Catalog:     "fz",
	New:         func(e *dql.Executor) any { return New(e) },
	NewExecutor: NewExecutor,
	Tables: map[string]any{
%s
	},
	Shapes: Shapes,
	Selects: map[string]any{
%s
	},
}
`, name, c.Seed, d, strings.Join(tables, "\n"), strings.Join(selects, "\n"))
}

// RunScenarios builds the packages Prepare wrote and runs each one's
// scenario, writing their results into out.
func (r *Run) RunScenarios(ctx context.Context, out string) error {
	cmd := exec.CommandContext(ctx, "go", "test", "-vet=off", "-count=1", "-timeout=2h", "-run", "^TestRun$", ".")
	cmd.Dir = r.Dir
	cmd.Env = append(os.Environ(), "GOWORK="+filepath.Join(r.Dir, "go.work"), OutEnv+"="+out)
	if b, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("running the scenarios: %w\n%s", err, b)
	}
	return nil
}
