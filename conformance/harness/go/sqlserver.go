// injectSQLServer sets the plan of conformance/schemas/sqlserver/inject.sql:
// the next in.Times writes wait for in.Delay, or else meet a real deadlock
// or lock timeout against a session of the harness's own, which it starts.
// It first ends the sessions an earlier plan started. Times 0 clears it.
func injectSQLServer(ctx context.Context, dsn string, in Inject) error {
	kind, ok := injectKinds[in.Class]
	var ms int64
	if in.Delay != "" {
		d, err := time.ParseDuration(in.Delay)
		if err != nil {
			return fmt.Errorf("delay: %w", err)
		}
		kind, ok, ms = "stall", true, d.Milliseconds()
	}
	if !ok && in.Times > 0 {
		return fmt.Errorf("no injected failure of class %s on SQL Server", in.Class)
	}
	if err := runSQLServer(ctx, dsn, fmt.Sprintf(`DECLARE @s INT, @kill NVARCHAR(32);
DECLARE helpers CURSOR LOCAL FAST_FORWARD FOR
  SELECT session_id FROM sys.dm_exec_sessions WHERE database_id = DB_ID() AND context_info = 0x64716C;
OPEN helpers;
FETCH NEXT FROM helpers INTO @s;
WHILE @@FETCH_STATUS = 0
BEGIN
  SET @kill = N'KILL ' + CAST(@s AS NVARCHAR(10));
  EXEC sp_executesql @kill;
  FETCH NEXT FROM helpers INTO @s;
END;
CLOSE helpers;
DEALLOCATE helpers;
DELETE FROM conformance.injection;
INSERT INTO conformance.injection VALUES ('%s', %d, %d);
ALTER SEQUENCE conformance.injected RESTART WITH 1;`, kind, in.Times, ms)); err != nil {
		return err
	}
	if helper := injectHelper(kind, in.Times); helper != "" {
		// The helper's session ends with its script, the next plan, or the
		// database. A write the plan fails waits for it to take its locks.
		go runSQLServer(context.Background(), dsn, helper)
	}
	return nil
}

// injectKinds are the plan's kinds of the classes a step injects.
var injectKinds = map[string]string{
	string(dql.ClassDeadlock):    "deadlock",
	string(dql.ClassLockTimeout): "lock_timeout",
}

// injectHelper is the script of the harness's session for a plan of kind
// and times: for a deadlock, each n-th time, it holds blocker row (n, 'b')
// until the write holds (n, 'a'), then waits for that row at high deadlock
// priority; for a lock timeout, it holds row (0, 'b') for a minute.
func injectHelper(kind string, times int) string {
	const head = "SET CONTEXT_INFO 0x64716C; SET DEADLOCK_PRIORITY HIGH;\n"
	switch {
	case times > 0 && kind == "deadlock":
		var b strings.Builder
		b.WriteString(head)
		for n := 1; n <= times; n++ {
			fmt.Fprintf(&b, `GO
BEGIN TRAN;
UPDATE conformance.blocker SET hits += 1 WHERE n = %d AND side = 'b';
EXEC conformance.held %d, 'a';
UPDATE conformance.blocker SET hits += 1 WHERE n = %d AND side = 'a';
COMMIT;
`, n, n, n)
		}
		return b.String()
	case times > 0 && kind == "lock_timeout":
		return head + `GO
BEGIN TRAN;
UPDATE conformance.blocker SET hits += 1 WHERE n = 0 AND side = 'b';
WAITFOR DELAY '00:01:00';
COMMIT;
`
	}
	return ""
}

// terminateSQLServer ends every other session on the database at dsn, as a
// server shutting them down would.
func terminateSQLServer(ctx context.Context, dsn string) error {
	db, err := sql.Open("sqlserver", dsn)
	if err != nil {
		return err
	}
	defer db.Close()
	var ids sql.NullString
	if err := db.QueryRowContext(ctx, `SELECT STRING_AGG(CAST(session_id AS varchar(10)), ',') FROM sys.dm_exec_sessions
WHERE database_id = DB_ID() AND session_id <> @@SPID AND is_user_process = 1`).Scan(&ids); err != nil {
		return err
	}
	for _, id := range strings.Split(ids.String, ",") {
		if id != "" {
			// A session may have ended on its own meanwhile.
			db.ExecContext(ctx, "KILL "+id)
		}
	}
	return nil
}

// replaySQLServer reports that SQL Server's schemas have no replica.
func replaySQLServer(context.Context, string, bool) error { return errNoReplica }

// errNoReplica is the error of pausing a replica that is not there.
var errNoReplica = errors.New("the SQL Server schemas have no replica")

// batches splits a script at its GO lines, as sqlcmd does.
var batches = regexp.MustCompile(`(?im)^[ \t]*GO[ \t]*$`)

// databaseSQLServer creates a database from the DDL files, in order, on the
// SQL Server base names, a URL without a database, and returns its URL and
// how to drop it.
func databaseSQLServer(ctx context.Context, base string, ddl ...string) (string, func(), error) {
	var script []string
	for _, f := range ddl {
		b, err := os.ReadFile(f)
		if err != nil {
			return "", nil, err
		}
		script = append(script, string(b))
	}
	u, err := url.Parse(base)
	if err != nil {
		return "", nil, err
	}
	name := fmt.Sprintf("conformance_%d_%d", os.Getpid(), time.Now().UnixNano())
	if err := runSQLServer(ctx, base, "CREATE DATABASE "+name); err != nil {
		return "", nil, err
	}
	drop := func() {
		runSQLServer(ctx, base, "IF DB_ID('"+name+"') IS NOT NULL BEGIN ALTER DATABASE "+name+" SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE "+name+" END")
	}
	q := u.Query()
	q.Set("database", name)
	u.RawQuery = q.Encode()
	dsn := u.String()
	if err := runSQLServer(ctx, dsn, strings.Join(script, "\nGO\n")); err != nil {
		drop()
		return "", nil, err
	}
	return dsn, drop, nil
}

// runSQLServer runs a script, its batches separated by GO lines, on a
// connection of its own to dsn, with the session settings the sqlserver
// dialect's connections have, which indexed computed columns need.
func runSQLServer(ctx context.Context, dsn, script string) error {
	db, err := sql.Open("sqlserver", dsn)
	if err != nil {
		return err
	}
	defer db.Close()
	c, err := db.Conn(ctx)
	if err != nil {
		return err
	}
	defer c.Close()
	for _, b := range append([]string{"SET ANSI_NULLS ON; SET QUOTED_IDENTIFIER ON; SET ARITHABORT ON"}, batches.Split(script, -1)...) {
		if strings.TrimSpace(b) == "" {
			continue
		}
		if _, err := c.ExecContext(ctx, b); err != nil {
			return err
		}
	}
	return nil
}
