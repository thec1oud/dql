// Package gen turns a bundle into the Go source files of one generated
// package (design record §15, §26.5). It reads only the bundle: every name,
// shape and conversion comes from the IR, never re-derived here.
package gen

import (
	"bytes"
	"cmp"
	"fmt"
	"go/format"
	"slices"
	"strings"

	irv1 "github.com/thec1oud/dql/proto/dql/ir/v1"
)

// Runtime is the Go runtime module generated code imports (§15).
const Runtime = "github.com/thec1oud/dql/runtime/go"

// CodeVersion is the generated-code version this emitter writes, which the
// runtime checks at compile time (§26.5).
const CodeVersion = 1

// Header is the first line of every generated file, in the form Go tools
// recognize as generated code. Files starting with it are the emitter's own:
// it replaces or removes them and leaves every other file alone (§26.5).
const Header = "// Code generated by dql. DO NOT EDIT."

// Suffix ends the name of every generated file.
const Suffix = ".dql.go"

// Diagnostic codes of the Go emitter. They are stable (implementation guide
// §7 rule 13).
const (
	// CodeNameCollision: two declarations of the generated package, or two
	// fields of one struct, get the same Go name after casing (§4.3, §15.2).
	CodeNameCollision = "go-name-collision"
	// CodeOpaqueUnmapped: an opaque type that the emitter's types setting
	// does not map and that has no fallback (§8.3).
	CodeOpaqueUnmapped = "go-opaque-unmapped"
)

// Options are the settings of one generated package.
type Options struct {
	// Package is the generated package's name.
	Package string
	// Types maps opaque native types, written namespace.type, to Go types:
	// a predeclared type such as string, or import/path.Name (§8.3).
	Types map[string]string
}

// File is one generated file.
type File struct {
	Name    string
	Content []byte
}

// Generate returns the files of the package b generates, sorted by name, and
// the diagnostics found, sorted (§3.2). With any error diagnostic it returns
// no files.
func Generate(b *irv1.Bundle, o Options) ([]File, []*irv1.Diagnostic) {
	g := newGenerator(b, o)
	g.version()
	g.types()
	g.shapes()
	if !g.failed() {
		// Conversions, merges, validators, decoders and redaction read the
		// shapes' types, so they wait for shapes without errors.
		g.conversions()
		g.merges()
		g.validators()
		g.decoders()
		g.redaction()
	}
	if g.failed() {
		sortDiagnostics(g.diags)
		return nil, g.diags
	}
	var files []File
	for _, f := range g.files {
		files = append(files, File{Name: f.name, Content: g.render(f)})
	}
	slices.SortFunc(files, func(a, b File) int { return strings.Compare(a.Name, b.Name) })
	sortDiagnostics(g.diags)
	return files, g.diags
}

type generator struct {
	b     *irv1.Bundle
	o     Options
	named map[key]named
	ix    shapeIndex
	files []*file
	// decls says what declares each package-level name so far.
	decls map[string]string
	// checks names the variable of each constraint's check by the
	// constraint's qualified name, declared in checkFile (§10.5).
	checks     map[string]string
	checkNames map[string]bool
	checkFile  *file
	// typesFile is dql-types.dql.go, and decoders the decoders of named
	// types declared in it so far (§13).
	typesFile     *file
	namedDecoders map[key]string
	diags         []*irv1.Diagnostic
}

// key identifies an object across catalogs.
type key struct{ catalog, namespace, object string }

func keyOf(q *irv1.QualifiedName) key {
	return key{q.GetCatalog(), q.GetNamespace(), q.GetObject()}
}

// named is an enum, domain or composite type a type can reference.
type named struct {
	words []string
	// base is a domain's base type, and q and constraints its name and
	// constraints.
	base        *irv1.Type
	q           *irv1.QualifiedName
	constraints []*irv1.Constraint
	// composite is a composite type's declaration.
	composite *irv1.Composite
}

func newGenerator(b *irv1.Bundle, o Options) *generator {
	g := &generator{b: b, o: o, named: map[key]named{}, decls: map[string]string{}, namedDecoders: map[key]string{}, checks: map[string]string{}, checkNames: map[string]bool{}}
	g.eachNamespace(func(q func(string) *irv1.QualifiedName, ns *irv1.Namespace) {
		for _, e := range ns.GetEnums() {
			g.named[keyOf(q(e.GetName().GetStored()))] = named{words: e.GetHostName().GetWords()}
		}
		for _, d := range ns.GetDomains() {
			g.named[keyOf(q(d.GetName().GetStored()))] = named{words: d.GetHostName().GetWords(), base: d.GetBase(), q: q(d.GetName().GetStored()), constraints: d.GetConstraints()}
		}
		for _, c := range ns.GetComposites() {
			g.named[keyOf(q(c.GetName().GetStored()))] = named{words: c.GetHostName().GetWords(), q: q(c.GetName().GetStored()), composite: c}
		}
	})
	g.indexShapes()
	return g
}

// eachNamespace calls fn for every namespace in IR order, with a function
// qualifying an object name in it.
func (g *generator) eachNamespace(fn func(q func(string) *irv1.QualifiedName, ns *irv1.Namespace)) {
	for _, c := range g.b.GetCatalogs() {
		for _, ns := range c.GetNamespaces() {
			fn(func(object string) *irv1.QualifiedName {
				return &irv1.QualifiedName{Catalog: c.GetName().GetStored(), Namespace: ns.GetName().GetStored(), Object: object}
			}, ns)
		}
	}
}

func (g *generator) failed() bool {
	return slices.ContainsFunc(g.diags, func(d *irv1.Diagnostic) bool { return d.GetSeverity() == irv1.Severity_SEVERITY_ERROR })
}

func (g *generator) errorf(code string, target *irv1.QualifiedName, format string, args ...any) {
	g.diags = append(g.diags, &irv1.Diagnostic{
		Severity: irv1.Severity_SEVERITY_ERROR,
		Code:     code,
		Target:   target,
		Message:  fmt.Sprintf(format, args...),
	})
}

// declare records a package-level Go name and what declares it, and fails a
// name declared twice (§4.3, §15.2): words that differ can still meet after
// casing, as [i d] and [id] both give ID, and generated names such as an
// enum's constants can meet another object's.
func (g *generator) declare(name, what string, target *irv1.QualifiedName) {
	if prev, ok := g.decls[name]; ok {
		g.errorf(CodeNameCollision, target, "%s gets the Go name %s, as %s does (§4.3, §15.2); give one of them a name annotation", what, name, prev)
		return
	}
	g.decls[name] = what
}

// file is one generated file under construction.
type file struct {
	name    string
	imports map[string]string // import path to package name
	body    bytes.Buffer
}

func (g *generator) newFile(name string) *file {
	f := &file{name: name + Suffix, imports: map[string]string{}}
	g.files = append(g.files, f)
	return f
}

// use imports path into f and returns the package name to qualify with.
func (f *file) use(path, name string) string {
	f.imports[path] = name
	return name
}

func (f *file) printf(format string, args ...any) {
	fmt.Fprintf(&f.body, format, args...)
}

// render returns f's source: the header (§26.5), the package clause, the
// imports, standard library first, and the body, formatted as gofmt does.
func (g *generator) render(f *file) []byte {
	var b bytes.Buffer
	b.WriteString(Header + "\n//\n")
	v := g.b.GetVersion()
	fmt.Fprintf(&b, "// IR version: %d.%d.%d\n", v.GetMajor(), v.GetMinor(), v.GetPatch())
	for _, c := range g.b.GetCatalogs() {
		fmt.Fprintf(&b, "// Input: catalog %s from %s %s, %s\n", c.GetName().GetStored(),
			c.GetProvenance().GetSource(), c.GetProvenance().GetSourceVersion(), c.GetProvenance().GetInputFingerprint())
	}
	fmt.Fprintf(&b, "// Runtime: %s, generated-code version %d\n\n", Runtime, CodeVersion)
	fmt.Fprintf(&b, "package %s\n", g.o.Package)
	var std, other []string
	for path := range f.imports {
		if strings.Contains(strings.Split(path, "/")[0], ".") {
			other = append(other, path)
		} else {
			std = append(std, path)
		}
	}
	slices.Sort(std)
	slices.Sort(other)
	if len(std)+len(other) > 0 {
		b.WriteString("\nimport (\n")
		for i, group := range [][]string{std, other} {
			if i == 1 && len(std) > 0 && len(other) > 0 {
				b.WriteString("\n")
			}
			for _, path := range group {
				if name := f.imports[path]; name != lastElement(path) {
					fmt.Fprintf(&b, "\t%s %q\n", name, path)
				} else {
					fmt.Fprintf(&b, "\t%q\n", path)
				}
			}
		}
		b.WriteString(")\n")
	}
	b.WriteString("\n")
	b.Write(f.body.Bytes())
	out, err := format.Source(b.Bytes())
	if err != nil {
		// The generator writes only valid Go, so this is a bug in it.
		panic(fmt.Sprintf("gen: %s does not format: %v\n%s", f.name, err, b.Bytes()))
	}
	return out
}

// lastElement is the last element of an import path.
func lastElement(path string) string {
	return path[strings.LastIndex(path, "/")+1:]
}

// sortDiagnostics sorts by severity, then qualified name, then code (§3.2).
func sortDiagnostics(ds []*irv1.Diagnostic) {
	slices.SortStableFunc(ds, func(a, b *irv1.Diagnostic) int {
		qa, qb := a.GetTarget(), b.GetTarget()
		return cmp.Or(
			cmp.Compare(a.GetSeverity(), b.GetSeverity()),
			strings.Compare(qa.GetCatalog(), qb.GetCatalog()),
			strings.Compare(qa.GetNamespace(), qb.GetNamespace()),
			strings.Compare(qa.GetObject(), qb.GetObject()),
			strings.Compare(qa.GetMember(), qb.GetMember()),
			strings.Compare(a.GetCode(), b.GetCode()),
		)
	})
}

// version declares the generated-code version the runtime checks (§26.5).
func (g *generator) version() {
	f := g.newFile("dql-version")
	dql := f.use(Runtime+"/dql", "dql")
	f.printf(`// The package fails to compile against a runtime that does not implement
// generated-code version %[1]d (§26.5).
const (
	_ = %[2]s.EnforceVersion(%[1]d - %[2]s.MinVersion)
	_ = %[2]s.EnforceVersion(%[2]s.MaxVersion - %[1]d)
)
`, CodeVersion, dql)
}
