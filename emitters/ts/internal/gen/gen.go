// Package gen turns a bundle into the TypeScript modules of one generated
// package (design record §15, §26.5). It reads only the bundle: every name,
// shape and conversion comes from the IR, never re-derived here.
//
// Generated modules are ESM TypeScript that uses only erasable syntax, so
// Node runs them with type stripping and Bun and Deno run them directly.
// Relative imports name the module's .ts file.
package gen

import (
	"bytes"
	"cmp"
	"fmt"
	"maps"
	"slices"
	"strings"

	irv1 "github.com/thec1oud/dql/proto/dql/ir/v1"
)

// Runtime is the runtime package generated code imports (§15).
const Runtime = "@dql/runtime"

// CodeVersion is the generated-code version this emitter writes, which the
// runtime checks when a generated module is imported (§26.5).
const CodeVersion = 1

// Header is the first line of every generated file. Files starting with it
// are the emitter's own: it replaces or removes them and leaves every other
// file alone (§26.5).
const Header = "// Code generated by dql. DO NOT EDIT."

// Suffix ends the name of every generated file.
const Suffix = ".dql.ts"

// Index is the generated module that re-exports every other one: the
// package's entry point.
const Index = "index" + Suffix

// Diagnostic codes of the TypeScript emitter. They are stable
// (implementation guide §7 rule 13).
const (
	// CodeNameCollision: two declarations of the generated package, or two
	// fields of one type, get the same TypeScript name after casing, or a
	// declaration takes a name generated code needs (§4.3, §15.2).
	CodeNameCollision = "ts-name-collision"
	// CodeOpaqueUnmapped: an opaque type that the emitter's types setting
	// does not map and that has no fallback (§8.3).
	CodeOpaqueUnmapped = "ts-opaque-unmapped"
	// CodeTypeUnknown: a type this emitter cannot map, such as a type kind of
	// a newer IR minor version, or a reference to a named type the bundle
	// lacks.
	CodeTypeUnknown = "ts-type-unknown"
)

// Options are the settings of one generated package.
type Options struct {
	// Types maps opaque native types, written namespace.type, to TypeScript
	// types: a built-in type such as string, or module#Name (§8.3).
	Types map[string]string
}

// File is one generated file.
type File struct {
	Name    string
	Content []byte
}

// Generate returns the files of the package b generates, sorted by name, and
// the diagnostics found, sorted (§3.2). With any error diagnostic it returns
// no files.
func Generate(b *irv1.Bundle, o Options) ([]File, []*irv1.Diagnostic) {
	g := newGenerator(b, o)
	g.version()
	g.types()
	g.shapes()
	if g.failed() {
		sortDiagnostics(g.diags)
		return nil, g.diags
	}
	g.index()
	var files []File
	for _, f := range g.files {
		files = append(files, File{Name: f.name, Content: g.render(f)})
	}
	slices.SortFunc(files, func(a, b File) int { return strings.Compare(a.Name, b.Name) })
	sortDiagnostics(g.diags)
	return files, g.diags
}

type generator struct {
	b     *irv1.Bundle
	o     Options
	named map[key]named
	ix    shapeIndex
	files []*file
	// decls says what declares each module-level name so far, and where.
	decls map[string]decl
	diags []*irv1.Diagnostic
	// reported holds each diagnostic's code, target and message, so that a
	// column every shape of an entity holds reports its type once.
	reported map[string]bool
}

// decl is a module-level name: what declares it, for diagnostics, and the
// file that exports it, empty for a name generated code takes from
// elsewhere.
type decl struct {
	what string
	file *file
}

// key identifies an object across catalogs.
type key struct{ catalog, namespace, object string }

func keyOf(q *irv1.QualifiedName) key {
	return key{q.GetCatalog(), q.GetNamespace(), q.GetObject()}
}

// named is an enum, domain or composite type a type can reference.
type named struct {
	words []string
}

// reserved are the names generated code takes from the runtime and from
// TypeScript's globals, which no declaration may take (§4.3).
var reserved = []string{
	// @dql/runtime
	"Cidr", "Decimal", "Inet", "JsonValue", "MacAddr", "OffsetTime", "Range", "Temporal", "Uuid", "Weak",
	// TypeScript globals
	"Array", "BigInt", "Boolean", "Date", "Error", "JSON", "Number", "Object", "Promise", "ReadonlyArray",
	"Record", "String", "Symbol", "Uint8Array",
}

func newGenerator(b *irv1.Bundle, o Options) *generator {
	g := &generator{b: b, o: o, named: map[key]named{}, decls: map[string]decl{}}
	for _, r := range reserved {
		what := "the TypeScript global " + r
		if slices.Contains(runtimeNames, r) {
			what = "the runtime's " + r
		}
		g.decls[r] = decl{what: what}
	}
	g.eachNamespace(func(q func(string) *irv1.QualifiedName, ns *irv1.Namespace) {
		for _, e := range ns.GetEnums() {
			g.named[keyOf(q(e.GetName().GetStored()))] = named{words: e.GetHostName().GetWords()}
		}
		for _, d := range ns.GetDomains() {
			g.named[keyOf(q(d.GetName().GetStored()))] = named{words: d.GetHostName().GetWords()}
		}
		for _, c := range ns.GetComposites() {
			g.named[keyOf(q(c.GetName().GetStored()))] = named{words: c.GetHostName().GetWords()}
		}
	})
	g.indexShapes()
	return g
}

// runtimeNames are the reserved names that come from the runtime.
var runtimeNames = reserved[:10]

// eachNamespace calls fn for every namespace in IR order, with a function
// qualifying an object name in it.
func (g *generator) eachNamespace(fn func(q func(string) *irv1.QualifiedName, ns *irv1.Namespace)) {
	for _, c := range g.b.GetCatalogs() {
		for _, ns := range c.GetNamespaces() {
			fn(func(object string) *irv1.QualifiedName {
				return &irv1.QualifiedName{Catalog: c.GetName().GetStored(), Namespace: ns.GetName().GetStored(), Object: object}
			}, ns)
		}
	}
}

func (g *generator) failed() bool {
	return slices.ContainsFunc(g.diags, func(d *irv1.Diagnostic) bool { return d.GetSeverity() == irv1.Severity_SEVERITY_ERROR })
}

func (g *generator) errorf(code string, target *irv1.QualifiedName, format string, args ...any) {
	msg := fmt.Sprintf(format, args...)
	k := fmt.Sprintf("%s\x00%v\x00%s\x00%s", code, keyOf(target), target.GetMember(), msg)
	if g.reported[k] {
		return
	}
	if g.reported == nil {
		g.reported = map[string]bool{}
	}
	g.reported[k] = true
	g.diags = append(g.diags, &irv1.Diagnostic{
		Severity: irv1.Severity_SEVERITY_ERROR,
		Code:     code,
		Target:   target,
		Message:  msg,
	})
}

// declare records a module-level name that f exports and what declares it,
// and fails a name declared twice (§4.3, §15.2): words that differ can still
// meet after casing, as [2fa] and [x2fa] both give X2fa, and a name
// can meet one generated code takes from the runtime or the globals.
func (g *generator) declare(f *file, name, what string, target *irv1.QualifiedName) {
	if prev, ok := g.decls[name]; ok {
		g.errorf(CodeNameCollision, target, "%s gets the TypeScript name %s, as %s does (§4.3, §15.2); give it a name annotation", what, name, prev.what)
		return
	}
	g.decls[name] = decl{what: what, file: f}
}

// file is one generated file under construction.
type file struct {
	name string
	// runtime holds the runtime's names f uses, true when one is used as a
	// value; modules holds, by module specifier, the names f imports from
	// other modules, by the same rule.
	runtime map[string]bool
	modules map[string]map[string]bool
	// sideEffects are modules f imports only to run them.
	sideEffects map[string]bool
	body        bytes.Buffer
}

func (g *generator) newFile(name string) *file {
	f := &file{name: name + Suffix, runtime: map[string]bool{}, modules: map[string]map[string]bool{}, sideEffects: map[string]bool{}}
	g.files = append(g.files, f)
	if name != "dql-version" {
		// Importing any module checks the runtime's version (§26.5).
		f.sideEffects["./dql-version"+Suffix] = true
	}
	return f
}

// rt returns name, imported into f from the runtime; value says whether f
// uses it as a value rather than only as a type.
func (f *file) rt(name string, value bool) string {
	f.runtime[name] = f.runtime[name] || value
	return name
}

// use imports name from module into f, as rt does from the runtime.
func (f *file) use(module, name string, value bool) string {
	if f.modules[module] == nil {
		f.modules[module] = map[string]bool{}
	}
	f.modules[module][name] = f.modules[module][name] || value
	return name
}

// ref returns a name the package declares, imported into f from the file
// that exports it.
func (g *generator) ref(f *file, name string, value bool) string {
	if d := g.decls[name]; d.file != nil && d.file != f {
		f.use("./"+d.file.name, name, value)
	}
	return name
}

func (f *file) printf(format string, args ...any) {
	fmt.Fprintf(&f.body, format, args...)
}

// render returns f's source: the header (§26.5), the imports, sorted, and
// the body.
func (g *generator) render(f *file) []byte {
	var b bytes.Buffer
	b.WriteString(Header + "\n//\n")
	v := g.b.GetVersion()
	fmt.Fprintf(&b, "// IR version: %d.%d.%d\n", v.GetMajor(), v.GetMinor(), v.GetPatch())
	for _, c := range g.b.GetCatalogs() {
		fmt.Fprintf(&b, "// Input: catalog %s from %s %s, %s\n", c.GetName().GetStored(),
			c.GetProvenance().GetSource(), c.GetProvenance().GetSourceVersion(), c.GetProvenance().GetInputFingerprint())
	}
	fmt.Fprintf(&b, "// Runtime: %s, generated-code version %d\n\n", Runtime, CodeVersion)
	modules := map[string]map[string]bool{}
	maps.Copy(modules, f.modules)
	if len(f.runtime) > 0 {
		modules[Runtime] = f.runtime
	}
	// The runtime and other packages first, then the package's own modules.
	specs := slices.SortedFunc(maps.Keys(modules), func(a, b string) int {
		return cmp.Or(cmp.Compare(boolInt(strings.HasPrefix(a, ".")), boolInt(strings.HasPrefix(b, "."))), strings.Compare(a, b))
	})
	for _, m := range slices.Sorted(maps.Keys(f.sideEffects)) {
		fmt.Fprintf(&b, "import %q;\n", m)
	}
	for _, m := range specs {
		names := modules[m]
		var parts []string
		allTypes := true
		for _, n := range slices.Sorted(maps.Keys(names)) {
			allTypes = allTypes && !names[n]
		}
		for _, n := range slices.Sorted(maps.Keys(names)) {
			if !names[n] && !allTypes {
				n = "type " + n
			}
			parts = append(parts, n)
		}
		kw := "import"
		if allTypes {
			kw = "import type"
		}
		fmt.Fprintf(&b, "%s { %s } from %q;\n", kw, strings.Join(parts, ", "), m)
	}
	if len(f.sideEffects)+len(modules) > 0 {
		b.WriteString("\n")
	}
	b.Write(bytes.TrimRight(f.body.Bytes(), "\n"))
	b.WriteString("\n")
	return b.Bytes()
}

func boolInt(b bool) int {
	if b {
		return 1
	}
	return 0
}

// sortDiagnostics sorts by severity, then qualified name, then code (§3.2).
func sortDiagnostics(ds []*irv1.Diagnostic) {
	slices.SortStableFunc(ds, func(a, b *irv1.Diagnostic) int {
		qa, qb := a.GetTarget(), b.GetTarget()
		return cmp.Or(
			cmp.Compare(a.GetSeverity(), b.GetSeverity()),
			strings.Compare(qa.GetCatalog(), qb.GetCatalog()),
			strings.Compare(qa.GetNamespace(), qb.GetNamespace()),
			strings.Compare(qa.GetObject(), qb.GetObject()),
			strings.Compare(qa.GetMember(), qb.GetMember()),
			strings.Compare(a.GetCode(), b.GetCode()),
		)
	})
}

// version checks the runtime's version when the package is imported (§26.5).
// Every other module imports this one.
func (g *generator) version() {
	f := g.newFile("dql-version")
	f.printf(`// The package fails to import with a runtime that does not implement
// generated-code version %[1]d (§26.5).
%[2]s(%[1]d);
`, CodeVersion, f.rt("enforceVersion", true))
}

// index re-exports every other module: the package's entry point.
func (g *generator) index() {
	f := &file{name: Index, runtime: map[string]bool{}, modules: map[string]map[string]bool{}, sideEffects: map[string]bool{}}
	names := make([]string, 0, len(g.files))
	for _, o := range g.files {
		names = append(names, o.name)
	}
	slices.Sort(names)
	for _, n := range names {
		f.printf("export * from %q;\n", "./"+n)
	}
	g.files = append(g.files, f)
}
