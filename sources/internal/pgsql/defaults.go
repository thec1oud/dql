// ClassifyDefault classifies a column default as pg_get_expr prints it, or as
// dpg writes it, by the classes of §11.3. Native keeps text exactly as given.
//
//   - A constant, possibly cast ('draft'::app.post_status, 1, true,
//     'x'::text, NULL), is DEFAULT_CONSTANT. Its value is a string, an int, a
//     decimal in exact text form (never a float, §8.7) or a bool, chosen by
//     the cast when there is one; NULL and bit strings have no value.
//   - nextval('seq'::regclass), the default of a serial column, is
//     DEFAULT_IDENTITY_BY_DEFAULT with the sequence: it is filled by the
//     database and may be overridden, as Postgres's GENERATED BY DEFAULT is.
//     The sequence's Catalog is the caller's to fill.
//   - Anything else (now(), gen_random_uuid()) is DEFAULT_EXPRESSION.
//
// Identity columns themselves (GENERATED ... AS IDENTITY) have no default
// expression; the source classifies them from the catalog. An error means
// text does not parse as an expression.
func ClassifyDefault(text string) (*irv1.Default, error) {
	expr, err := parseDefault(text)
	if err != nil {
		return nil, err
	}
	d := &irv1.Default{Class: irv1.DefaultClass_DEFAULT_EXPRESSION, Native: text}
	if seq := nextvalSequence(expr); seq != nil {
		d.Class, d.Sequence = irv1.DefaultClass_DEFAULT_IDENTITY_BY_DEFAULT, seq
		return d, nil
	}
	target := ""
	for expr.GetTypeCast() != nil {
		if target == "" {
			target = typeKey(expr.GetTypeCast().TypeName)
		}
		expr = expr.GetTypeCast().Arg
	}
	if c := expr.GetAConst(); c != nil {
		d.Class, d.Value = irv1.DefaultClass_DEFAULT_CONSTANT, constValue(c, target)
	}
	return d, nil
}

// typeKey names a cast target: a pg_catalog type by its name, anything else
// (which only ever yields a string) as "other".
func typeKey(tn *pg.TypeName) string {
	if name, ok := builtinName(tn); ok && len(tn.ArrayBounds) == 0 {
		return name
	}
	return "other"
}

// nextvalSequence returns the sequence of nextval('name'), with or without
// Postgres's ::regclass cast, or nil.
func nextvalSequence(expr *pg.Node) *irv1.QualifiedName {
	f := expr.GetFuncCall()
	fn, _ := names(f.GetFuncname())
	if len(fn) == 2 && fn[0] == "pg_catalog" {
		fn = fn[1:]
	}
	if len(fn) != 1 || fn[0] != "nextval" || len(f.Args) != 1 {
		return nil
	}
	arg := f.Args[0]
	if tc := arg.GetTypeCast(); tc != nil {
		if name, ok := builtinName(tc.TypeName); !ok || name != "regclass" {
			return nil
		}
		arg = tc.Arg
	}
	s := arg.GetAConst().GetSval()
	if s == nil {
		return nil
	}
	parts, ok := splitRelationName(s.Sval)
	switch {
	case !ok:
		return nil
	case len(parts) == 1:
		return &irv1.QualifiedName{Object: parts[0]}
	case len(parts) == 2:
		return &irv1.QualifiedName{Namespace: parts[0], Object: parts[1]}
	}
	return nil
}

// splitRelationName splits a relation name as regclass input reads it:
// dot-separated identifiers, double-quoted ones kept exactly (with "" for a
// quote), unquoted ones lower-cased in ASCII as Postgres does.
func splitRelationName(s string) ([]string, bool) {
	var parts []string
	for {
		var part strings.Builder
		if strings.HasPrefix(s, `"`) {
			s = s[1:]
			for {
				i := strings.IndexByte(s, '"')
				if i < 0 {
					return nil, false
				}
				part.WriteString(s[:i])
				s = s[i+1:]
				if !strings.HasPrefix(s, `"`) {
					break
				}
				part.WriteByte('"')
				s = s[1:]
			}
		} else {
			i := strings.IndexAny(s, `."`)
			if i < 0 {
				i = len(s)
			}
			for _, b := range []byte(s[:i]) {
				if b >= 'A' && b <= 'Z' {
					b += 'a' - 'A'
				}
				part.WriteByte(b)
			}
			s = s[i:]
		}
		if part.Len() == 0 {
			return nil, false
		}
		parts = append(parts, part.String())
		if s == "" {
			return parts, true
		}
		if s[0] != '.' {
			return nil, false
		}
		s = s[1:]
	}
}

// constValue reads a constant default's value; target is its outermost cast,
// or empty. It returns nil for NULL, bit strings and text a numeric or
// boolean cast would not read exactly.
func constValue(c *pg.A_Const, target string) *irv1.Value {
	var text string
	switch {
	case c.Isnull, c.GetBsval() != nil:
		return nil
	case c.GetBoolval() != nil:
		if target == "" || target == "bool" {
			return &irv1.Value{Kind: &irv1.Value_Bool{Bool: c.GetBoolval().Boolval}}
		}
		text = strconv.FormatBool(c.GetBoolval().Boolval)
	case c.GetIval() != nil:
		text = strconv.FormatInt(int64(c.GetIval().Ival), 10)
	case c.GetFval() != nil:
		text = c.GetFval().Fval
	default:
		text = c.GetSval().Sval
	}
	if target == "" && c.GetSval() == nil {
		// An uncast number: integers are ints, others decimals.
		target = "numeric"
		if _, err := strconv.ParseInt(text, 10, 64); err == nil {
			target = "int8"
		}
	}
	switch target {
	case "int2", "int4", "int8":
		if v, err := strconv.ParseInt(text, 10, 64); err == nil {
			return &irv1.Value{Kind: &irv1.Value_Int{Int: v}}
		}
		return nil
	case "numeric", "float4", "float8":
		if decimalText.MatchString(text) {
			return &irv1.Value{Kind: &irv1.Value_Decimal{Decimal: text}}
		}
		return nil
	case "bool":
		if v, ok := pgBool(text); ok {
			return &irv1.Value{Kind: &irv1.Value_Bool{Bool: v}}
		}
		return nil
	}
	return &irv1.Value{Kind: &irv1.Value_String_{String_: text}}
}

// pgBool reads the full words Postgres's boolean input accepts.
func pgBool(s string) (bool, bool) {
	switch strings.ToLower(strings.Trim(s, " \t\n\r\f\v")) {
	case "t", "true", "y", "yes", "on", "1":
		return true, true
	case "f", "false", "n", "no", "off", "0":
		return false, true
	}
	return false, false
}
